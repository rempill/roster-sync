import assert from "node:assert/strict";
import { chromium } from "playwright";
import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const artifacts = fileURLToPath(new URL("../artifacts/", import.meta.url));
await mkdir(artifacts, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
const failures = [];
page.on("pageerror", error => failures.push(error.message));
try {
  await page.goto(process.env.WEB_URL || "http://localhost:3000");
  await page.getByRole("button", { name: "Explore the demo" }).click();
  await page.getByRole("heading", { name: "Find your project team" }).waitFor();
  await page.getByText("Live updates", { exact: true }).waitFor();
  assert(await page.getByRole("heading", { name: "StudyFlow", exact: true }).count());
  await page.screenshot({ path: artifacts + "dashboard-desktop.png", fullPage: true });
  await page.locator(".profile-switch").click();
  await page.getByRole("button", { name: "New here? Create an account", exact: true }).click();
  await page.getByLabel("Your name", { exact: true }).fill("Browser Student");
  await page.getByLabel("University email", { exact: true }).fill("browsertest" + Date.now() + "@stud.ubbcluj.ro");
  await page.getByLabel("Password", { exact: true }).fill("Test12345!");
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await page.getByRole("heading", { name: "Find your project team" }).waitFor();
  await page.getByRole("textbox", { name: "Search teams" }).fill("Campus Connect");
  assert.equal(await page.locator(".team-card").count(), 1);
  await page.getByRole("textbox", { name: "Search teams" }).fill("");
  await page.getByRole("navigation").getByRole("button", { name: "Profile", exact: true }).click();
  await page.getByLabel("Your skills, separated by commas").fill("React,TypeScript,Python");
  await page.getByRole("button", { name: "Save profile", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "Profile updated" }).waitFor();
  await page.getByRole("navigation").getByRole("button", { name: "Schedule", exact: true }).click();
  const slot = page.getByRole("button", { name: "Mon 9:00", exact: true });
  const before = await slot.getAttribute("aria-pressed");
  await slot.click();
  assert.notEqual(await slot.getAttribute("aria-pressed"), before);
  await page.getByRole("button", { name: "Save availability" }).click();
  await page.getByRole("status").filter({ hasText: "Availability saved" }).waitFor();
  await page.reload();
  await page.getByRole("navigation").getByRole("button", { name: "Schedule", exact: true }).click();
  assert.notEqual(await page.getByRole("button", { name: "Mon 9:00", exact: true }).getAttribute("aria-pressed"), before);
  await page.getByLabel("Week starting Monday").fill("2026-11-09");
  await page.getByLabel("Calendar file").setInputFiles(fileURLToPath(new URL("../../branch2/demo-calendar.ics", import.meta.url)));
  await page.getByRole("button", { name: "Import calendar", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "2 calendar events imported" }).waitFor();
  assert.equal(await page.getByRole("button", { name: "Mon 10:00", exact: true }).getAttribute("aria-pressed"), "false");
  await page.getByLabel("Compare with a team").selectOption("demo-studyflow");
  assert(await page.locator(".slot.shared").count() > 0);
  await page.screenshot({ path: artifacts + "schedule-desktop.png", fullPage: true });
  await page.getByRole("navigation").getByRole("button", { name: "Discover", exact: true }).click();
  await page.locator(".team-card").filter({ has: page.getByRole("heading", { name: "StudyFlow", exact: true }) }).getByRole("button", { name: "Apply", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "Application sent" }).waitFor();
  await page.getByRole("navigation").getByRole("button", { name: "Requests", exact: true }).click();
  assert(await page.getByText("Browser Student applied to StudyFlow", { exact: true }).count());
  await page.getByRole("navigation").getByRole("button", { name: "Discover", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: artifacts + "dashboard-mobile.png", fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  assert.deepEqual(failures, []);
  console.log("PASS Browser login, live connection, search, profile, schedule persistence, ICS import, heatmap, application, requests and mobile layout");
} finally {
  await browser.close();
}
